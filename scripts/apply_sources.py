def make_backup():
    ts = datetime.now().strftime('%Y%m%d_%H%M%S')
    backup = os.path.join(ROOT, f'_BACKUP_до_источников_{ts}.docx')
    shutil.copy2(TARGET, backup)
    print(f'  Бэкап: {os.path.basename(backup)}')


def main():
    print('=== Реструктуризация источников по ГОСТ ===\n')
    make_backup()
    doc = Document(TARGET)

    # Найдём шаблон обычного абзаца для клонирования стиля
    body_tpl = find_template_paragraph(
        doc, lambda p: p.text.startswith('Объектом разработки выступает'))

    # Заголовок СПИСКА — последний параграф с этим текстом (в основном тексте)
    paragraphs = list(doc.paragraphs)
    header_idx = None
    for i, p in enumerate(paragraphs):
        if p.text.strip() == 'СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ':
            header_idx = i  # сохраняем последний
    if header_idx is None:
        print('ОШИБКА: не найден заголовок СПИСКА')
        return

    # Найдём конец списка — параграф ПРИЛОЖЕНИЕ или ПЕРЕЧЕНЬ или конец документа
    end_idx = len(paragraphs)
    for i in range(header_idx + 1, len(paragraphs)):
        t = paragraphs[i].text.strip()
        if t.startswith('ПРИЛОЖЕНИЕ') or t.startswith('ПЕРЕЧЕНЬ'):
            end_idx = i
            break

    print(f'Зона источников: параграфы [{header_idx+1}..{end_idx-1}]')

    # Удаляем все параграфы в этой зоне
    to_remove = paragraphs[header_idx + 1:end_idx]
    for p in to_remove:
        remove_paragraph(p)
    print(f'Удалено старых пунктов: {len(to_remove)}')

    # Вставляем новый список
    header = paragraphs[header_idx]
    cursor = header
    counter = 0

    sections = [
        ('Нормативно-правовые акты', NORMATIVE),
        ('Стандарты', STANDARDS),
        ('Учебная и научная литература', LITERATURE),
        ('Электронные ресурсы и спецификации', ELECTRONIC),
    ]

    for title, items in sections:
        # Пустая строка-отбивка
        cursor = insert_paragraph_after(cursor, '')
        # Подзаголовок раздела (полужирный)
        cursor = insert_paragraph_after(cursor, title, bold=True)
        for item in items:
            counter += 1
            cursor = insert_paragraph_after(
                cursor, f'{counter}. {item}', clone_from=body_tpl)

    # Финальная пустая строка
    insert_paragraph_after(cursor, '')

    doc.save(TARGET)
    print(f'\n✓ Вставлен новый список: {counter} позиций в {len(sections)} разделах')
    print(f'  • Нормативно-правовые акты: {len(NORMATIVE)}')
    print(f'  • Стандарты: {len(STANDARDS)}')
    print(f'  • Учебная и научная литература: {len(LITERATURE)}')
    print(f'  • Электронные ресурсы и спецификации: {len(ELECTRONIC)}')


if __name__ == '__main__':
    main()

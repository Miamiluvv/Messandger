def apply_global_replacements(doc, log):
    count = 0
    for p in doc.paragraphs:
        for old, new in GLOBAL_REPLACEMENTS:
            if old in p.text:
                # Заменяем сохраняя стиль первого run
                full = p.text.replace(old, new)
                set_paragraph_text(p, full)
                count += 1
    # Таблицы
    for tab in doc.tables:
        for row in tab.rows:
            for cell in row.cells:
                for p in cell.paragraphs:
                    for old, new in GLOBAL_REPLACEMENTS:
                        if old in p.text:
                            set_paragraph_text(p, p.text.replace(old, new))
                            count += 1
    log.append(f'Глобальных замен: {count}')



def make_backup():
    ts = datetime.now().strftime('%Y%m%d_%H%M%S')
    backup = os.path.join(ROOT, f'_BACKUP_до_текстов_{ts}.docx')
    shutil.copy2(TARGET, backup)
    print(f'  Бэкап: {os.path.basename(backup)}')


def main():
    print('=== Текстовые вставки: интеграция / звонки / редактор / безопасность ===\n')
    make_backup()
    doc = Document(TARGET)
    log = []

    body_tpl = find_template_paragraph(
        doc, lambda p: p.text.startswith('Архитектура системы спроектирована'))
    head_tpl = find_template_paragraph(
        doc, lambda p: p.text.startswith('2.6 Размещение мессенджера'))
    caption_tpl = find_template_paragraph(
        doc, lambda p: p.text.strip().startswith('Рисунок 17 — '))

    # ── A. Авторизация → точка интеграции ──────────────────
    auth_para = find_paragraph_starts_with(
        doc, "Безопасность доступа к API обеспечивается посредством")
    if auth_para is not None:
        set_paragraph_text(auth_para, INTEGRATION_NEW)
        log.append('A. Точка интеграции вставлена')
    else:
        log.append('A. Якорь авторизации НЕ найден')

    # ── B. Звонки — после абзаца про рис. 17 ───────────────
    calls_anchor = find_paragraph_starts_with(
        doc, "В интерфейсе звонка")
    if calls_anchor is not None:
        last = insert_paragraphs_after(calls_anchor, CALLS, clone_from=body_tpl)
        last = insert_paragraph_after(last, FIG_CALL_INIT,
                                        clone_from=caption_tpl)
        log.append(f'B. Описание звонков вставлено ({len(CALLS)} абз.) + подпись 17а')
    else:
        log.append('B. Якорь звонков НЕ найден')

    # ── C. Редактор фото — перед абзацем про опросы ────────
    polls_anchor = find_paragraph_starts_with(
        doc, "Для принятия групповых решений")
    if polls_anchor is not None:
        prev = previous_paragraph(doc, polls_anchor)
        last = insert_paragraphs_after(prev, EDITOR, clone_from=body_tpl)
        last = insert_paragraph_after(last, FIG_EDITOR, clone_from=caption_tpl)
        log.append(f'C. Описание редактора фото вставлено ({len(EDITOR)} абз.) + подпись 17б')
    else:
        log.append('C. Якорь опросов НЕ найден')

    # ── D. Безопасность — подраздел 2.6.1 перед 2.7 ────────
    chat_anchor = find_paragraph_starts_with(
        doc, "2.7 Алгоритм создания группового чата")
    if chat_anchor is not None:
        prev = previous_paragraph(doc, chat_anchor)
        last = insert_paragraph_after(prev, SEC_HEADING, bold=True,
                                        clone_from=head_tpl)
        last = insert_paragraphs_after(last, SECURITY, clone_from=body_tpl)
        log.append(f'D. Подраздел 2.6.1 безопасности добавлен ({len(SECURITY)} абз.)')
    else:
        log.append('D. Якорь 2.7 НЕ найден')

    doc.save(TARGET)
    print('\n--- Журнал ---')
    for l in log:
        print(' ', l)
    print(f'\n✓ Сохранено: {os.path.basename(TARGET)}')


if __name__ == '__main__':
    main()

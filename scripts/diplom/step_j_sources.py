def run(doc):
    """Заменяет существующий список источников новым структурированным."""
    # Найдём якорь
    header = find_paragraph_starts_with(doc, "СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ")
    if header is None:
        print("[J] WARN: не найден заголовок списка источников")
        return

    # Найти границу — параграф ПРИЛОЖЕНИЕ А (или ПЕРЕЧЕНЬ если до заголовка)
    all_p = list(doc.paragraphs)
    start_idx = find_index_of_paragraph(doc, header)
    if start_idx < 0:
        print("[J] WARN: не удалось найти индекс заголовка")
        return
    end_idx = None
    for j in range(start_idx + 1, len(all_p)):
        txt = all_p[j].text.strip()
        if txt.startswith("ПРИЛОЖЕНИЕ") or txt.startswith("Приложение"):
            end_idx = j
            break
    if end_idx is None:
        end_idx = len(all_p)

    # Удаляем все параграфы между заголовком и приложением (не включая
    # сам header и сам ПРИЛОЖЕНИЕ).
    to_remove = all_p[start_idx + 1: end_idx]
    for p in to_remove:
        # Пропускаем полностью пустые параграфы — оставим один для отбивки
        remove_paragraph(p)

    # Шаблоны
    body_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("Архитектура системы спроектирована"))

    cursor = header
    counter = 0
    for section_title, items in SOURCES.items():
        cursor = insert_paragraph_after(cursor, "")  # отбивка
        cursor = insert_paragraph_after(cursor, section_title, bold=True)
        for item in items:
            counter += 1
            cursor = insert_paragraph_after(
                cursor, f"{counter}. {item}",
                clone_from=body_template,
            )

    insert_paragraph_after(cursor, "")
    print(f"[J] Список источников переструктурирован: {counter} позиций "
          f"в {len(SOURCES)} разделах")

def run(doc):
    # Шаблоны: обычный абзац и подпись рисунка
    body_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("Архитектура системы спроектирована"))
    caption_template = find_template_paragraph(
        doc, lambda p: p.text.strip().startswith("Рисунок 17 — "))
    if caption_template is None:
        caption_template = find_template_paragraph(
            doc, lambda p: p.text.strip().startswith("Рисунок 1 — "))

    # Звонки — после абзаца про рисунок 17
    anchor = find_paragraph_starts_with(doc, "В интерфейсе звонка")
    if anchor is not None:
        last = insert_paragraphs_after(anchor, CALLS, clone_from=body_template)
        for line in CALLS_FIGURES:
            last = insert_paragraph_after(last, line,
                                            clone_from=caption_template)

    # Редактор фото — перед абзацем про опросы (рис. 18)
    target = find_paragraph_starts_with(doc, "Для принятия групповых решений")
    if target is not None:
        prev = previous_paragraph(doc, target)
        last = insert_paragraphs_after(prev, EDITOR, clone_from=body_template)
        for line in EDITOR_FIGURES:
            last = insert_paragraph_after(last, line,
                                            clone_from=caption_template)

    print("[F] Описание звонков и редактора фото добавлено (стиль клонирован)")

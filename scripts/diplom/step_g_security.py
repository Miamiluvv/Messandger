def run(doc):
    # Раздел вставляем ПЕРЕД "2.7 Алгоритм создания группового чата" —
    # это логичное место: после "2.6 Размещение мессенджера" сразу идёт
    # обеспечение безопасности, а потом — частный алгоритм группового
    # чата. Раздел получает номер 2.6.1.

    anchor = find_paragraph_starts_with(doc,
        "2.7 Алгоритм создания группового чата")
    if anchor is None:
        for p in doc.paragraphs:
            if p.text.startswith("2.7 Алгоритм"):
                anchor = p
                break

    if anchor is None:
        # запасной вариант — перед 2.8
        anchor = find_paragraph_starts_with(doc, "2.8 Тестирование")

    if anchor is None:
        print("[G] WARN: не найден якорь для вставки раздела безопасности")
        return

    # Вставляем перед anchor
    prev = previous_paragraph(doc, anchor)

    # Берём шаблоны: заголовок раздела (2.6) и обычный абзац основного текста
    heading_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("2.6 Размещение мессенджера"))
    body_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("Архитектура системы спроектирована"))

    # Заголовок 2.6.1 — клонируем стиль заголовка 2.6
    heading = insert_paragraph_after(
        prev,
        "2.6.1 Обеспечение информационной безопасности системы",
        bold=True, clone_from=heading_template,
    )
    # Тело — клонируем стиль обычного абзаца
    insert_paragraphs_after(heading, SECURITY, clone_from=body_template)
    print("[G] Раздел безопасности добавлен как 2.6.1 (стиль клонирован)")

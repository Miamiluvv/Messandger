# -*- coding: utf-8 -*-
"""Замена раздела авторизации на интеграционный."""
from docx.enum.text import WD_ALIGN_PARAGRAPH
from .helpers import (set_paragraph_text, insert_paragraphs_after,
                      find_paragraph_starts_with, find_template_paragraph)


INTEGRATION_TEXT = [
    "Аутентификация пользователей в системе реализована как точка интеграции "
    "с единой корпоративной системой идентификации Правительства Москвы. "
    "Такой подход обеспечивает «бесшовный» вход (single sign-on) сотрудников "
    "Департамента городского имущества города Москвы во все ведомственные "
    "информационные системы по единым учётным данным, выдаваемым Управлением "
    "информатизации.",

    "На стороне мессенджера предусмотрены универсальные интеграционные "
    "интерфейсы (API), к которым подключается внешняя система аутентификации. "
    "Сам мессенджер не хранит пароли пользователей в открытом виде и не "
    "выполняет первичной проверки учётных данных — эта функция полностью "
    "делегирована корпоративной системе. После успешной идентификации "
    "пользователю выдаётся токен доступа JWT (JSON Web Token), подписанный "
    "по алгоритму HMAC-SHA256, который используется для всех последующих "
    "запросов к серверу мессенджера.",

    "Преимущества такого подхода: централизованное управление учётными "
    "записями (создание, блокировка, заморозка) выполняется в одном месте; "
    "политика паролей соответствует общекорпоративным требованиям; "
    "сотрудник работает с одной парой логин/пароль для всех систем; при "
    "увольнении сотрудника достаточно отключить его учётную запись в "
    "корпоративной системе — доступ ко всем интегрированным сервисам "
    "прекращается автоматически. Применительно к коду мессенджера это "
    "означает, что модуль аутентификации спроектирован с чёткими точками "
    "расширения: при подключении к корпоративной системе изменяется только "
    "реализация одной функции проверки учётных данных, тогда как все "
    "остальные модули системы (чаты, звонки, уведомления) остаются "
    "неизменными.",
]


def run(doc):
    # Переподписи рисунков 8, 11, 13
    rename = {
        "Рисунок 8 — Листинг кода: эндпоинт авторизации (FastAPI)":
            "Рисунок 8 — Листинг кода: модуль интеграции с единой "
            "корпоративной системой аутентификации",

        "Рисунок 11 — Листинг кода: Zustand-хранилище авторизации":
            "Рисунок 11 — Листинг кода: клиентское хранилище сессии",

        "Рисунок 13 — Страница входа в систему":
            "Рисунок 13 — Точка входа через единую корпоративную "
            "аутентификацию",
    }
    for p in doc.paragraphs:
        for old, new in rename.items():
            if old in p.text:
                set_paragraph_text(p, p.text.replace(old, new))

    # Замена описаний после рис. 8, 11, 13
    desc_map = [
        ("Как показано на рисунке 8, эндпоинт",
         "Как показано на рисунке 8, модуль интеграции реализует "
         "универсальный программный интерфейс для подключения к внешней "
         "корпоративной системе аутентификации. Перед обращением к внешней "
         "системе выполняется ограничение скорости запросов (rate limiting) "
         "на уровне сервера мессенджера: после пяти неуспешных попыток "
         "подряд комбинация «адрес электронной почты + IP-адрес клиента» "
         "блокируется на пятнадцать минут. Это защищает не только сам "
         "мессенджер, но и внешнюю систему аутентификации от атак подбора "
         "паролей. После успешной проверки учётных данных сервер "
         "мессенджера выдаёт JWT-токен, в полезной нагрузке которого "
         "размещаются идентификатор пользователя, его роль в системе и "
         "срок действия токена. Токен автоматически продлевается каждые "
         "10 минут активной работы через эндпоинт обновления сессии — это "
         "исключает ситуации, когда сотрудник вынужден повторно входить "
         "в систему во время текущей рабочей сессии."),

        ("Хранилище useAuthStore (рисунок 11) предоставляет",
         "Клиентское хранилище сессии (рисунок 11) предоставляет "
         "компонентам приложения единый интерфейс для работы с текущим "
         "пользователем: получение профиля, автоматическое продление "
         "токена, безопасный выход из системы. JWT-токен сохраняется в "
         "браузерном хранилище, для всех HTTP-запросов автоматически "
         "добавляется заголовок Authorization: Bearer <token>. При "
         "получении ответа 401 или 403 от сервера токен удаляется и "
         "пользователь перенаправляется на корпоративную страницу "
         "входа — это гарантирует, что интерфейс мессенджера никогда "
         "не остаётся в несогласованном состоянии с внешней системой "
         "аутентификации."),

        ("На странице входа (рисунок 13) пользователь вводит",
         "Точка входа в систему (рисунок 13) построена как тонкий "
         "интерфейсный слой, передающий введённые сотрудником учётные "
         "данные в единую корпоративную систему аутентификации. В случае "
         "утери пароля или необходимости получения учётной записи "
         "сотруднику предоставляется ссылка для подачи заявки в "
         "Управление информатизации Департамента, которое осуществляет "
         "первичное создание и блокировку учётных записей в "
         "корпоративной системе. Сам мессенджер при этом получает "
         "информацию о статусе пользователя только через "
         "стандартизированный API корпоративной аутентификации."),
    ]
    for prefix, new_text in desc_map:
        p = find_paragraph_starts_with(doc, prefix)
        if p is not None:
            set_paragraph_text(p, new_text)

    # Вставка дополнительных абзацев про точку интеграции после описания рис. 8
    anchor = find_paragraph_starts_with(doc, "Как показано на рисунке 8, модуль интеграции")
    if anchor is not None:
        body_template = find_template_paragraph(
            doc, lambda p: p.text.startswith("Архитектура системы спроектирована"))
        insert_paragraphs_after(anchor, INTEGRATION_TEXT,
                                 clone_from=body_template)
    print("[D] Раздел авторизации заменён точкой интеграции (стиль клонирован)")

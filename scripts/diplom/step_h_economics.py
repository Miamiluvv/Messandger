def run(doc):
    # 1. Замены ключевых формулировок
    for marker, new_text in REPLACEMENTS.items():
        p = find_paragraph_starts_with(doc, marker)
        if p is not None:
            set_paragraph_text(p, new_text)

    # Шаблоны
    body_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("Архитектура системы спроектирована"))
    heading_template = find_template_paragraph(
        doc, lambda p: p.text.startswith("3.5 Анализ эффективности"))
    if heading_template is None:
        heading_template = find_template_paragraph(
            doc, lambda p: p.text.startswith("2.6 Размещение мессенджера"))

    # Вставка нового абзаца с раскладкой расчёта после фразы про формулу
    anchor = find_paragraph_starts_with(doc,
        "Расчёт годовой экономии бюджетных средств выполняется по формуле")
    if anchor is not None:
        insert_paragraphs_after(anchor, [NEW_CALC_PARAGRAPH],
                                 clone_from=body_template)

    # 2. Замены в разделе 3.5
    for marker, new_text in REPLACEMENTS_EFFICIENCY.items():
        p = find_paragraph_starts_with(doc, marker)
        if p is not None:
            set_paragraph_text(p, new_text)

    # 3. Подмена чисел в таблицах 10-13
    cell_map = {
        "10 634 770": "8 814 098",
        "10\u00a0634\u00a0770": "8\u00a0814\u00a0098",
        "6 798 577": "5 433 073",
        "6\u00a0798\u00a0577": "5\u00a0433\u00a0073",
        "63,9 %": "61,6 %",
        "63,9%": "61,6%",
        "286 %": "128,7 %",
        "286%": "128,7%",
        "4,2 месяца": "5,25 месяца",
        "4,2 мес": "5,25 мес",
        "83,4 млн": "8,81 млн",
        "1500 × 0,042 × 247 × 682": "600 × 0,0833 × 247 × 714",
        "2,9 рубля": "1,29 рубля",
    }
    replace_in_table_cells(doc, cell_map)
    # И в обычных параграфах
    for p in doc.paragraphs:
        old = p.text
        new = old
        for s, r in cell_map.items():
            new = new.replace(s, r)
        if new != old:
            set_paragraph_text(p, new)

    # 4. Подраздел 3.6
    end_anchor = find_paragraph_starts_with(doc,
        "Таким образом, разработка и внедрение защищённого корпоративного")
    if end_anchor is None:
        # Альтернатива
        end_anchor = find_paragraph_starts_with(doc,
            "Таким образом, разработка и внедрение")

    if end_anchor is not None:
        prev = previous_paragraph(doc, end_anchor)
        # Заголовок — клонируем стиль существующего заголовка раздела
        first = insert_paragraphs_after(prev, [INFORMATION_VALUE[0]],
                                          bold=True,
                                          clone_from=heading_template)
        # Тело — клонируем стиль обычного абзаца
        insert_paragraphs_after(first, INFORMATION_VALUE[1:],
                                 clone_from=body_template)

    print("[H,I] Экономическая часть пересчитана + добавлен подраздел 3.6")
